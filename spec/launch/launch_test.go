func load(t *testing.T, sandbox string) *spec.Manifest {
	t.Helper()
	a, err := spec.LoadArtifactFromBytes([]byte("schemaVersion: \"2\"\nkind: sandbox\nname: k\nsandbox:\n  image: img\n" + sandbox))
	require.NoError(t, err)
	return &a.Manifest
}

func TestFromManifest(t *testing.T) {
	tests := []struct {
		name string
		m    *spec.Manifest
		want Recipe
	}{
		{
			name: "v2 list command",
			m:    load(t, "  entrypoint: [agent, sub]\n  command: [--model, sonnet]\n"),
			want: Recipe{Version: 1, Kind: KindAgent, Binary: "agent", FixedArgs: []string{"sub"}, DefaultArgs: []string{"--model", "sonnet"}},
		},
		{
			name: "v2 interactive wins",
			m:    load(t, "  entrypoint: [agent]\n  command:\n    default: [--headless]\n    interactive: [--tui]\n"),
			want: Recipe{Version: 1, Kind: KindAgent, Binary: "agent", DefaultArgs: []string{"--tui"}},
		},
		{
			name: "v2 absent interactive uses default",
			m:    load(t, "  entrypoint: [agent]\n  command:\n    default: [--headless]\n"),
			want: Recipe{Version: 1, Kind: KindAgent, Binary: "agent", DefaultArgs: []string{"--headless"}},
		},
		{
			name: "v2 empty interactive means no tail",
			m:    load(t, "  entrypoint: [agent, sub]\n  command:\n    default: [--headless]\n    interactive: []\n"),
			want: Recipe{Version: 1, Kind: KindAgent, Binary: "agent", FixedArgs: []string{"sub"}},
		},
		{
			name: "v2 shell kit",
			m:    load(t, "  command: [-l]\n"),
			want: Recipe{Version: 1, Kind: KindShell},
		},
		{
			name: "flat only",
			m:    &spec.Manifest{Binary: "agent", RunOptions: []string{"--a", "b"}},
			want: Recipe{Version: 1, Kind: KindAgent, Binary: "agent", DefaultArgs: []string{"--a", "b"}, Legacy: true},
		},
		{
			name: "flat interactive preferred",
			m:    &spec.Manifest{Binary: "agent", RunOptions: []string{"--a"}, InteractiveOptions: []string{"--i"}},
			want: Recipe{Version: 1, Kind: KindAgent, Binary: "agent", DefaultArgs: []string{"--i"}, Legacy: true},
		},
		{
			// A child that extends claude with command [--model, sonnet]
			// after a field-by-field merge: the flat fields hold the
			// effective command, Launch is the parent's. The recipe must
			// not bring the parent's permission flag back.
			name: "inherited stale launch",
			m: &spec.Manifest{
				Binary:             "claude",
				RunOptions:         []string{"--model", "sonnet"},
				InteractiveOptions: []string{"--model", "sonnet"},
				Launch:             &spec.Launch{Entrypoint: []string{"claude", "--dangerously-skip-permissions"}},
			},
			want: Recipe{Version: 1, Kind: KindAgent, Binary: "claude", DefaultArgs: []string{"--model", "sonnet"}, Legacy: true},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := FromManifest(tt.m)
			require.Equal(t, tt.want, got)
			require.NoError(t, got.Validate())
		})
	}
}

func TestValidate(t *testing.T) {
	bad := []Recipe{
		{Version: 2, Kind: KindAgent, Binary: "a"},
		{Version: 1, Kind: "other", Binary: "a"},
		{Version: 1, Kind: KindAgent},
		{Version: 1, Kind: KindAgent, Binary: "-a"},
		{Version: 1, Kind: KindAgent, Binary: "a", FixedArgs: []string{"x"}, Legacy: true},
		{Version: 1, Kind: KindAgent, Binary: "a", DefaultArgs: []string{"x\x00y"}},
		{Version: 1, Kind: KindShell, Binary: "bash"},
		{Version: 1, Kind: KindShell, DefaultArgs: []string{"-l"}},
	}
	for _, r := range bad {
		require.Error(t, r.Validate(), "%+v", r)
		_, err := Render(r)
		require.Error(t, err)
	}
	_, err := Render(Recipe{Version: 1, Kind: KindShell})
	require.Error(t, err, "a shell recipe has no launcher")
}

